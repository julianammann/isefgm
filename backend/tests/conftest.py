class FixedClock:
    """Pinned `now` for the app; a test moves it forward with `advance`."""

    def __init__(self, now: datetime) -> None:
        self.current = now

    def now(self) -> datetime:
        return self.current

    def advance(self, delta: timedelta) -> None:
        self.current += delta


