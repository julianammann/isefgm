# --- Requirement traceability (QZ-01, Q-09) -----------------------------------
# Tests declare the MS 1 requirements they cover: @pytest.mark.requirement("F-01", "Q-03").
# After a full run the matrix "requirement -> test -> outcome" is written to
# docs/generated/traceability.md; it is part of the MS 4 test report.
# Partial runs (-k, a single file) overwrite it with a partial matrix, so
# regenerate with a full `mise run test` before committing. See docs/dokumentation.md.

TRACEABILITY_OUT = Path(__file__).resolve().parents[2] / "docs" / "generated"
_requirements: dict[str, list[str]] = {}  # nodeid -> requirement ids
_outcomes: dict[str, str] = {}  # nodeid -> passed | failed | skipped


def pytest_collection_finish(session: pytest.Session) -> None:
    for item in session.items:
        ids = {str(rid) for mark in item.iter_markers("requirement") for rid in mark.args}
        _requirements[item.nodeid] = sorted(ids)


def pytest_runtest_logreport(report: pytest.TestReport) -> None:
    # Setup/teardown failures count too; a passed setup does not.
    if report.when == "call" or report.outcome != "passed":
        _outcomes[report.nodeid] = report.outcome


def pytest_sessionfinish(session: pytest.Session) -> None:
    if session.config.getoption("collectonly") or not _outcomes:
        return
    by_requirement: dict[str, list[str]] = {}
    unmapped: list[str] = []
    for nodeid, ids in _requirements.items():
        if not ids:
            unmapped.append(nodeid)
        for rid in ids:
            by_requirement.setdefault(rid, []).append(nodeid)

    lines = [
        "<!-- Generated by pytest (tests/conftest.py). Do not edit by hand. -->",
        "",
        "# Traceability: requirement ↔ test",
        "",
        "Requirement IDs from `docs/ms1_projektkonfiguration.md`. "
        + "Outcome of the last full test run.",
        "",
        "| Requirement | Test | Outcome |",
        "| --- | --- | --- |",
    ]
    lines.extend(
        f"| {rid} | `{nodeid}` | {_outcomes.get(nodeid, 'not run')} |"
        for rid in sorted(by_requirement)
        for nodeid in by_requirement[rid]
    )
    if unmapped:
        lines += ["", "## Tests without a requirement", ""]
        lines += [f"- `{nodeid}`" for nodeid in sorted(unmapped)]
    TRACEABILITY_OUT.mkdir(parents=True, exist_ok=True)
    (TRACEABILITY_OUT / "traceability.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8", newline="\n"
    )
